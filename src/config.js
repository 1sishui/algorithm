/** 算法诊断：数据页「算法诊断」把每个大类判成 强 / 中 / 弱 */
export const VERDICT_CONFIG = {
  /**
   * 判「强」的第一个条件：通过率 ≥ 0.7
   * 取值理由：0.7 大致等于「十道题能自己做出七道」，是多数同学眼中的"会"；
   * 低于这个值就说明这一类有明显短板，不该判强。判强比判弱危险——判弱只是多推荐几道题，
   * 判强会让人跳过该练的东西，所以这条要严。
   */
  strongRate: 0.7,

  /**
   * 判「强」的第二个条件：平均每题提交次数 ≤ 2.2
   * 取值理由：2.2 表示「大多数题一两次就过，允许个别题反复调」。
   * 超过 2.2 说明还在试错，不能算稳。它和通过率是「并且」关系，两个都满足才判强。
   */
  strongMaxAttempts: 2.2,

  /**
   * 判「弱」的第一个条件（满足即弱）：通过率 < 0.4
   * 取值理由：十道题做不出四道，基本可以判定这一类没掌握。
   * 判弱用的是「或者」关系：通过率低或提交次数多，任一成立就判弱（宽松，宁可多提醒）。
   */
  weakRate: 0.4,

  /**
   * 判「弱」的第二个条件（满足即弱）：平均每题提交次数 ≥ 4
   * 取值理由：平均要交四次以上，通常意味着靠试错撞出来的，而不是掌握了方法。
   * 注意：它和六维里「尝试模式」用的中位数口径不同（这里是均值），换口径要先看文档。
   */
  weakMinAttempts: 4,

  /**
   * 诊断表最多显示多少个大类
   * 取值理由：目前归并表有 9 个算法大类 + 「其他」，12 是留了余量——
   * 以后新增标签不会立刻被截掉。纯展示项，不影响任何判定结果。
   */
  maxCategories: 12
};

/**
 * 汇总入口：以后六维、分析流程的常量也加到这里，保持「一个地方找所有可调项」。
 * 用法：import { CONFIG } from './config.js'; CONFIG.verdict.strongRate
 */
export const CONFIG = {
  verdict: VERDICT_CONFIG
};

