const CATEGORY_NAMES = RULES.map(([category]) => category);

/** 单个标签 → 大类 */
export function categoryOfTag(name) {
  const text = String(name || '')
    .replace(/\ufeff/g, '')
    .trim();
  if (!text) return '其他';

  // 标签名本身就等于大类（如「数学」「图论」）
  if (CATEGORY_NAMES.includes(text)) return text;

  for (const [category, keywords] of RULES) {
    for (const keyword of keywords) {
      if (text.includes(keyword)) return category;
    }
  }
  return '其他';
}

/** 一组标签 → 去重后的大类列表 */
export function categoriesOfTags(tags) {
  const result = [];
  for (const tag of tags || []) {
    const category = categoryOfTag(tag);
    if (category && !result.includes(category)) result.push(category);
  }
  return result;
}
/**
 * 判断一个标签是不是“非算法标签”。
 * 老版本抓取时把年份（2005）、比赛来源（NOIP 普及组、USACO）也存了进来，
 * 这些统一当噪音过滤掉，避免它们全落进「其他」。
 */
const NOISE_PATTERN = /^(19|20)\d{2}$|NOIP|NOI|USACO|ICPC|CCPC|GESP|CSP|省选|联赛|杯|公开赛|月赛|组$|赛$/;

export function isNoiseTag(name) {
  const text = String(name || '')
    .replace(/\ufeff/g, '')
    .trim();
  if (!text) return true;
  if (/^\d+$/.test(text)) return true;
  return NOISE_PATTERN.test(text);
}